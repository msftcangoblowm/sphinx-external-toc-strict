@pytest.mark.parametrize(
    "final",
    (
        pytest.param(
            None,
            id="None",
        ),
        pytest.param(
            0.12345,
            id="unsupported type",
        ),
        pytest.param(
            False,
            id="False",
        ),
    ),
)
def test_finals(
    args: tuple[int, int, int],
    kwargs: "dict[str, str | int]",
    actual: str,
    final: "float | bool | None",
) -> None:
    """Used for display only. Allows release level, final"""
    # Flip the logic backwards
    expect_info, expect_dev = get_version(
        actual,
        is_use_final=final,
    )
    assert kwargs["dev"] == expect_dev
    assert kwargs["serial"] == expect_info[-1]
    if len(kwargs["releaselevel"]) == 0:
        assert len(expect_info[-2]) == 0
    else:
        assert kwargs["releaselevel"] == expect_info[-2]
    assert args == expect_info[:3]


def test_final_allow() -> None:
    """Test get_version."""
    # Allow final
    actual = "1.0.1"
    l_actual = actual.split(".")
    l_actual2 = map(int, iter(l_actual))
    t_actual = tuple(l_actual2)
    expect_info, expect_dev = get_version(
        actual,
        is_use_final=True,
    )
    assert 0 == expect_dev
    assert 0 == expect_info[-1]
    assert "final" == expect_info[-2]
    assert t_actual == expect_info[:3]


@pytest.mark.parametrize(
    "v_in, expected_in",
    (
        pytest.param(
            "0.1.1.a1dev1+g4b33a80.d20240129",
            "0.1.1a1.dev1",
            id="a1.dev1",
        ),
        pytest.param(
            "0.1.1.alpha1dev1+g4b33a80.d20240129",
            "0.1.1a1.dev1",
            id="alpha1dev1",
        ),
        pytest.param(
            "0.1.1.b1dev1+g4b33a80.d20240129",
            "0.1.1b1.dev1",
            id="b1dev1",
        ),
        pytest.param(
            "0.1.1.beta1dev1+g4b33a80.d20240129",
            "0.1.1b1.dev1",
            id="beta1dev1",
        ),
        pytest.param(
            "0.1.1.rc1dev1+g4b33a80.d20240129",
            "0.1.1rc1.dev1",
            id="rc1dev1",
        ),
    ),
)
def test_dev_and_prerelease(v_in: str, expected_in: str) -> None:
    """Test sanitize_tag with dev and pre-release version str."""
    # Has both dev and is a prerelease
    expected = sanitize_tag(v_in)
    expect_info, expect_dev = get_version(expected)

    v = Version(expected)

    # v_pre = v.pre
    # v_pre_is = v.is_prerelease
    v_dev = v.dev

    # long format
    pre = expect_info[-2]
    assert pre in _map_release

    found_k = None
    for k in _map_release:
        if pre == k:
            found_k = k

    assert expect_dev == v_dev

    assert found_k is not None
    # pre is long format. So ``alpha`` rather than ``a``
    assert pre == found_k


