@pytest.mark.parametrize(
    "t_ver, ver_expected",
    (
        pytest.param(
            (0, 5, 2),
            "0.5.2",
            id="x.y.z",
        ),
        pytest.param(
            (0, 5, 2, "dev0"),
            "0.5.2.dev0",
            id="x.y.z.dev0",
        ),
        pytest.param(
            (0, 5, 2, "dev0", "g1234567.d20240101"),
            "0.5.2.dev0+g1234567.d20240101",
            id="x.y.z.dev0+local",
        ),
    ),
)
def test_setuptools_scm_version_file(
    t_ver: "tuple[int | str, ...]",
    ver_expected: str,
) -> None:
    """Autogenerated file by setuptools-scm"""
    ver = list(t_ver[:3])
    ver_short = ".".join(map(str, ver))
    if len(t_ver) == 3:
        # 0.0.1
        ver_long = ver_short
        ver_actual = ver_long
    elif len(t_ver) in (4, 5):
        # __version_tuple__
        # 0.0.1.a1dev8
        ver_dev = t_ver[3]
        ver_long = ver_short
        if len(ver_dev) != 0:
            ver_long += f".{ver_dev}"
        if len(t_ver) == 4:
            ver_actual = ver_long
        else:
            ver_git = t_ver[-1]
            ver_actual = f"{ver_long}+{ver_git}"

    assert ver_actual == ver_expected


