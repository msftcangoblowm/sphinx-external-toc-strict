@pytest.mark.parametrize(
    "package_name",
    (
        pytest.param(
            "this-that",
            id="package-name-has-hyphens",
        ),
        pytest.param(
            "this_that",
            id="app_name-has-underscores",
        ),
    ),
)
def test_readthedocs_package_name(ver: str, package_name: str) -> None:
    """Test readthedocs_url. What if package name contains periods!"""
    str_url = readthedocs_url(package_name, ver_=ver)
    protocol_len = len("https://")
    uri = str_url[protocol_len:]
    package_name = uri.split(".")[0]
    assert "_" not in package_name
